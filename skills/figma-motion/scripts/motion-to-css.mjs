#!/usr/bin/env node
// figma-master: turn Figma keyframes (from read-motion.js) into plain CSS animations.
// Usage: node motion-to-css.mjs <motion.json> [--loop]
// Output: CSS on stdout. Warnings on stderr.
// Plays ONCE by default (Figma's own export loops forever). Add --loop to repeat.
// Supports: OPACITY, TRANSLATION_X/Y/XY, SCALE_X/Y/XY, ROTATION.
// Not supported (listed in a comment): fills, strokes, effects, size, corner radius, path trim.
import { readFileSync } from "node:fs";

const args = process.argv.slice(2);
const file = args.find((a) => !a.startsWith("--"));
if (!file) { console.error("Usage: node motion-to-css.mjs <motion.json> [--loop]"); process.exit(2); }
const loop = args.includes("--loop");
const data = JSON.parse(readFileSync(file, "utf8"));
if (!data.nodes) { console.error("Input needs { nodes }. Make it with read-motion.js."); process.exit(3); }

const warn = (m) => console.error("warning: " + m);
const SUPPORTED = ["OPACITY", "TRANSLATION_X", "TRANSLATION_Y", "TRANSLATION_XY", "SCALE_X", "SCALE_Y", "SCALE_XY", "ROTATION"];

// Figma easing -> CSS. Standard curves match Motion's named eases. Springs are approximated.
const EASE = {
  LINEAR: "linear",
  EASE_IN: "cubic-bezier(0.42, 0, 1, 1)",
  EASE_OUT: "cubic-bezier(0, 0, 0.58, 1)",
  EASE_IN_AND_OUT: "cubic-bezier(0.42, 0, 0.58, 1)",
  EASE_IN_BACK: "cubic-bezier(0.36, 0, 0.66, -0.56)",
  EASE_OUT_BACK: "cubic-bezier(0.34, 1.56, 0.64, 1)",
  EASE_IN_AND_OUT_BACK: "cubic-bezier(0.68, -0.6, 0.32, 1.6)",
  GENTLE: "cubic-bezier(0.25, 1, 0.5, 1)",
  QUICK: "cubic-bezier(0.2, 1, 0.3, 1)",
  BOUNCY: "cubic-bezier(0.34, 1.56, 0.64, 1)",
  SLOW: "cubic-bezier(0.16, 1, 0.3, 1)",
};
const easeCss = (e, label) => {
  if (!e || !e.type) return "linear";
  // Figma sends the real curve with most easings. Use it when it is there.
  if (e.easingFunctionCubicBezier && e.type !== "CUSTOM_SPRING") {
    const c = e.easingFunctionCubicBezier;
    return `cubic-bezier(${c.x1}, ${c.y1}, ${c.x2}, ${c.y2})`;
  }
  if (e.type === "CUSTOM_SPRING" || ["GENTLE", "QUICK", "BOUNCY", "SLOW"].includes(e.type)) warn(`${label}: spring ${e.type} approximated with a cubic-bezier.`);
  if (e.type === "HOLD") return "steps(1, end)";
  return EASE[e.type] || (warn(`${label}: unknown easing ${e.type}, used linear.`), "linear");
};

const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "") || "layer";
const used = new Map();
const className = (name) => {
  const base = "fm-" + slug(name);
  const n = (used.get(base) || 0) + 1;
  used.set(base, n);
  return n === 1 ? base : `${base}-${n}`;
};
const round = (x) => +(+x).toFixed(4);

// value of a track at time t: hold before first, hold after last, linear between
const at = (kfs, t) => {
  if (t <= kfs[0].timelinePosition) return kfs[0].value;
  const last = kfs[kfs.length - 1];
  if (t >= last.timelinePosition) return last.value;
  for (let i = 0; i < kfs.length - 1; i++) {
    const a = kfs[i], b = kfs[i + 1];
    if (t >= a.timelinePosition && t <= b.timelinePosition) {
      const k = (t - a.timelinePosition) / (b.timelinePosition - a.timelinePosition || 1);
      if (a.value.type === "VECTOR") {
        return { type: "VECTOR", value: { x: a.value.value.x + (b.value.value.x - a.value.value.x) * k, y: a.value.value.y + (b.value.value.y - a.value.value.y) * k } };
      }
      return { type: "FLOAT", value: a.value.value + (b.value.value - a.value.value) * k };
    }
  }
  return last.value;
};

const out = [];
const classMap = [];
const reducedRules = [];
const header = [
  `/* Generated by figma-master from Figma keyframes. Screen: ${data.root ? data.root.name : "unknown"}. */`,
  `/* Plays ${loop ? "on a loop" : "once"}. Add each class to the matching element. */`,
];

for (const node of data.nodes) {
  const cls = className(node.name);
  const fields = Object.keys(node.tracks).filter((f) => SUPPORTED.includes(f));
  const skipped = Object.keys(node.tracks).filter((f) => !SUPPORTED.includes(f));
  if (skipped.length) warn(`${node.name}: not converted: ${skipped.join(", ")}.`);
  if (!fields.length) continue;

  const times = [...new Set(fields.flatMap((f) => node.tracks[f].keyframes.map((k) => round(k.timelinePosition))))].sort((a, b) => a - b);
  if (times.length < 2) { warn(`${node.name}: only one keyframe time, skipped.`); continue; }
  const start = times[0], end = times[times.length - 1], span = end - start;

  // warn when tracks do not share keyframe times (values in between are interpolated)
  for (const f of fields) {
    const own = new Set(node.tracks[f].keyframes.map((k) => round(k.timelinePosition)));
    if (own.size !== times.length) warn(`${node.name}: ${f} has different keyframe times than other tracks. Values between are interpolated linearly.`);
  }

  // easing for segment i->i+1 comes from the keyframe at times[i+1]
  const segEase = (i) => {
    const t = times[i + 1];
    for (const f of fields) {
      const kf = node.tracks[f].keyframes.find((k) => round(k.timelinePosition) === t);
      if (kf && kf.easing) return easeCss(kf.easing, `${node.name}.${f}`);
    }
    return "linear";
  };

  const val = (f, t) => at(node.tracks[f].keyframes, t);
  const frames = times.map((t, i) => {
    const pct = round(((t - start) / span) * 100);
    const decl = [];
    const parts = [];
    if (fields.includes("TRANSLATION_XY")) { const v = val("TRANSLATION_XY", t).value; parts.push(`translate(${round(v.x)}px, ${round(v.y)}px)`); }
    else if (fields.includes("TRANSLATION_X") || fields.includes("TRANSLATION_Y")) {
      const x = fields.includes("TRANSLATION_X") ? val("TRANSLATION_X", t).value : 0;
      const y = fields.includes("TRANSLATION_Y") ? val("TRANSLATION_Y", t).value : 0;
      parts.push(`translate(${round(x)}px, ${round(y)}px)`);
    }
    if (fields.includes("ROTATION")) parts.push(`rotate(${round(-val("ROTATION", t).value)}deg)`); // Figma counter clockwise is positive
    if (fields.includes("SCALE_XY")) { const v = val("SCALE_XY", t).value; parts.push(`scale(${round(v.x)}, ${round(v.y)})`); }
    else if (fields.includes("SCALE_X") || fields.includes("SCALE_Y")) {
      const x = fields.includes("SCALE_X") ? val("SCALE_X", t).value : 1;
      const y = fields.includes("SCALE_Y") ? val("SCALE_Y", t).value : 1;
      parts.push(`scale(${round(x)}, ${round(y)})`);
    }
    if (parts.length) decl.push(`transform: ${parts.join(" ")};`);
    if (fields.includes("OPACITY")) decl.push(`opacity: ${round(val("OPACITY", t).value)};`);
    if (i < times.length - 1) decl.push(`animation-timing-function: ${segEase(i)};`);
    return `  ${pct}% { ${decl.join(" ")} }`;
  });

  out.push(`@keyframes ${cls} {\n${frames.join("\n")}\n}`);
  out.push(`.${cls} {\n  animation: ${cls} ${round(span)}s linear ${loop ? "infinite" : "1"} both;\n  animation-delay: ${round(start)}s;\n}`);
  classMap.push(`${cls}  <-  ${node.name}${node.parent ? ` (in ${node.parent})` : ""}`);

  // reduced motion: keep a short opacity fade, drop movement
  if (fields.includes("OPACITY")) {
    const kfs = node.tracks.OPACITY.keyframes;
    out.push(`@keyframes ${cls}-reduced {\n  0% { opacity: ${round(kfs[0].value.value)}; }\n  100% { opacity: ${round(kfs[kfs.length - 1].value.value)}; }\n}`);
    reducedRules.push(`  .${cls} { animation: ${cls}-reduced 0.15s ease-out 1 both; animation-delay: ${round(start)}s; }`);
  } else {
    reducedRules.push(`  .${cls} { animation: none; }`);
  }
}

if (!out.length) { console.error("Nothing to convert."); process.exit(4); }
if (data.unsupportedTrackGroups && data.unsupportedTrackGroups.length) {
  header.push(`/* Not converted (no CSS written): ${data.unsupportedTrackGroups.join(", ")} tracks. */`);
}
header.push("/* Classes:\n" + classMap.map((l) => "   " + l).join("\n") + "\n*/");
console.log(header.join("\n") + "\n\n" + out.join("\n\n") + `\n\n@media (prefers-reduced-motion: reduce) {\n${reducedRules.join("\n")}\n}`);
